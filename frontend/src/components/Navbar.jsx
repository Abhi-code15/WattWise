import React, { useState, useEffect } from 'react';
import { Link, useLocation } from 'react-router-dom';
import { 
  Zap, 
  LayoutDashboard, 
  Map, 
  AlertTriangle, 
  BarChart3, 
  Cpu, 
  Sliders, 
  LogOut, 
  Bell, 
  Radio, 
  Home, 
  CheckCircle,
  HelpCircle,
  ExternalLink
} from 'lucide-react';
import { useAuth } from '../context/AuthContext';
import { useSocket } from '../context/SocketContext';
import { api } from '../services/api';
import ThemeToggle from './ThemeToggle';

export default function Navbar() {
  const { user, logout } = useAuth();
  const { isConnected } = useSocket();
  const location = useLocation();

  const [notifications, setNotifications] = useState([]);
  const [unreadCount, setUnreadCount] = useState(0);
  const [showNotifications, setShowNotifications] = useState(false);

  useEffect(() => {
    async function loadNotifications() {
      try {
        const res = await api.get('/notifications');
        if (res.success) {
          setNotifications(res.data);
          setUnreadCount(res.unreadCount);
        }
      } catch {
        // Ignore failure
      }
    }
    loadNotifications();
    const interval = setInterval(loadNotifications, 15000);
    return () => clearInterval(interval);
  }, []);

  const markAsRead = async (id) => {
    try {
      await api.post(`/notifications/${id}/read`, {});
      setNotifications(prev => prev.map(n => n.id === id ? { ...n, isRead: true } : n));
      setUnreadCount(prev => Math.max(0, prev - 1));
    } catch (err) {
      console.error(err);
    }
  };

  const isWarden = user?.role === 'WARDEN';

  const wardenLinks = [
    { to: '/warden', label: 'Overview', icon: LayoutDashboard },
    { to: '/warden/floors', label: 'Hostel Map', icon: Map },
    { to: '/warden/rooms', label: 'Room Monitor', icon: Home },
    { to: '/warden/alerts', label: 'Alerts', icon: AlertTriangle },
    { to: '/warden/analytics', label: 'Analytics', icon: BarChart3 },
    { to: '/warden/meters', label: 'Meters', icon: Cpu },
    { to: '/warden/simulator', label: 'Simulator', icon: Radio },
    { to: '/warden/settings', label: 'Tariff & Config', icon: Sliders }
  ];

  const studentLinks = [
    { to: '/student', label: 'My Room Dashboard', icon: Home }
  ];

  const links = isWarden ? wardenLinks : studentLinks;

  return (
    <header className="sticky top-0 z-50 bg-white/95 dark:bg-slate-900/95 backdrop-blur-md border-b border-slate-200 dark:border-slate-800 transition-colors">
      {/* Top Banner Bar */}
      <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8">
        <div className="flex items-center justify-between h-16">
          
          {/* Logo & Simulated Data Badge */}
          <div className="flex items-center space-x-3">
            <Link to={isWarden ? '/warden' : '/student'} className="flex items-center space-x-2">
              <div className="w-10 h-10 rounded-xl bg-gradient-to-tr from-blue-600 to-cyan-500 flex items-center justify-center shadow-lg shadow-blue-500/20">
                <Zap className="w-6 h-6 text-white" />
              </div>
              <div className="flex flex-col">
                <span className="text-xl font-extrabold tracking-tight text-slate-900 dark:text-white flex items-center gap-1.5">
                  WattWise
                  <span className="text-xs px-1.5 py-0.5 rounded bg-blue-500/10 text-blue-600 dark:text-blue-400 font-semibold border border-blue-500/20">Hostel A</span>
                </span>
                <span className="text-[10px] text-slate-500 dark:text-slate-400 font-medium tracking-wide">IoT Energy Intelligence</span>
              </div>
            </Link>

            {/* MANDATORY SIMULATED DATA BADGE */}
            <div className="hidden sm:flex items-center space-x-1.5 px-2.5 py-1 rounded-full bg-amber-500/10 border border-amber-500/30 text-amber-600 dark:text-amber-400 text-xs font-semibold" title="All telemetry generated by deterministic virtual smart-meter simulation engine">
              <span className="w-2 h-2 rounded-full bg-amber-400 animate-ping" />
              <span>SIMULATED DATA</span>
            </div>
          </div>

          {/* Right Status & Profile Controls */}
          <div className="flex items-center space-x-2 sm:space-x-3">
            
            {/* Live Socket Status */}
            <div className="flex items-center space-x-2 px-2.5 py-1 rounded-full bg-slate-100 dark:bg-slate-800 border border-slate-200 dark:border-slate-700 text-xs">
              <span className={`w-2.5 h-2.5 rounded-full ${isConnected ? 'bg-emerald-500 animate-pulse' : 'bg-rose-500'}`} />
              <span className="font-mono text-slate-700 dark:text-slate-300 font-medium">{isConnected ? 'LIVE' : 'CONNECTING'}</span>
            </div>

            {/* Theme Toggle Button */}
            <ThemeToggle />

            {/* Notifications Popover */}
            <div className="relative">
              <button 
                onClick={() => setShowNotifications(!showNotifications)}
                className="relative p-2 rounded-xl bg-slate-100 hover:bg-slate-200 dark:bg-slate-800 dark:hover:bg-slate-700 text-slate-700 dark:text-slate-300 transition"
                title="Notifications"
              >
                <Bell className="w-5 h-5" />
                {unreadCount > 0 && (
                  <span className="absolute -top-1 -right-1 w-5 h-5 rounded-full bg-rose-500 text-white text-[11px] font-bold flex items-center justify-center">
                    {unreadCount}
                  </span>
                )}
              </button>

              {showNotifications && (
                <div className="absolute right-0 mt-2 w-80 sm:w-96 bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-700 rounded-xl shadow-2xl p-4 z-50">
                  <div className="flex items-center justify-between pb-3 border-b border-slate-200 dark:border-slate-800">
                    <span className="font-bold text-slate-900 dark:text-white text-sm">Notifications ({unreadCount} unread)</span>
                    <button 
                      onClick={() => setShowNotifications(false)}
                      className="text-xs text-slate-500 dark:text-slate-400 hover:text-slate-900 dark:hover:text-white"
                    >
                      Close
                    </button>
                  </div>

                  <div className="max-h-72 overflow-y-auto divide-y divide-slate-100 dark:divide-slate-800 mt-2">
                    {notifications.length === 0 ? (
                      <p className="text-xs text-slate-400 text-center py-6">No notifications received</p>
                    ) : (
                      notifications.map(n => (
                        <div 
                          key={n.id} 
                          className={`py-2.5 px-2 transition rounded flex flex-col space-y-1 ${n.isRead ? 'opacity-60' : 'bg-slate-50 dark:bg-slate-800/40'}`}
                        >
                          <div className="flex items-center justify-between">
                            <span className="text-xs font-semibold text-slate-900 dark:text-white">{n.title}</span>
                            {!n.isRead && (
                              <button 
                                onClick={() => markAsRead(n.id)}
                                className="text-[10px] text-blue-600 dark:text-blue-400 hover:underline flex items-center gap-1"
                              >
                                <CheckCircle className="w-3 h-3" /> Mark read
                              </button>
                            )}
                          </div>
                          <p className="text-xs text-slate-600 dark:text-slate-300">{n.message}</p>
                          <span className="text-[10px] text-slate-400">{new Date(n.createdAt).toLocaleTimeString()}</span>
                        </div>
                      ))
                    )}
                  </div>
                </div>
              )}
            </div>

            {/* User Profile Badge */}
            <div className="flex items-center space-x-2 pl-2 border-l border-slate-200 dark:border-slate-800">
              <div className="flex flex-col text-right">
                <span className="text-sm font-semibold text-slate-900 dark:text-slate-200">{user?.name}</span>
                <span className="text-[10px] font-bold uppercase tracking-wider text-blue-600 dark:text-blue-400">
                  {user?.role === 'WARDEN' ? 'Chief Warden' : `Student (${user?.assignedRooms?.[0]?.roomCode || 'Room'})`}
                </span>
              </div>
              <button
                onClick={logout}
                className="p-2 rounded-xl bg-slate-100 hover:bg-rose-50 text-slate-600 hover:text-rose-600 dark:bg-slate-800 dark:hover:bg-rose-900/40 dark:text-slate-400 dark:hover:text-rose-300 transition"
                title="Sign Out"
              >
                <LogOut className="w-4 h-4" />
              </button>
            </div>

          </div>
        </div>
      </div>

      {/* Navigation Links Bar */}
      <div className="bg-slate-50/80 dark:bg-slate-900/60 border-t border-slate-200 dark:border-slate-800/60 px-4 sm:px-6 lg:px-8">
        <div className="max-w-7xl mx-auto flex items-center justify-between">
          <nav className="flex items-center space-x-1 sm:space-x-2 overflow-x-auto py-2">
            {links.map((link) => {
              const Icon = link.icon;
              const isActive = location.pathname === link.to;
              return (
                <Link
                  key={link.to}
                  to={link.to}
                  className={`flex items-center space-x-2 px-3 py-1.5 rounded-lg text-xs font-semibold whitespace-nowrap transition ${
                    isActive
                      ? 'bg-blue-600 text-white shadow-md shadow-blue-600/30'
                      : 'text-slate-600 dark:text-slate-400 hover:text-slate-900 dark:hover:text-slate-200 hover:bg-slate-200/60 dark:hover:bg-slate-800'
                  }`}
                >
                  <Icon className="w-4 h-4" />
                  <span>{link.label}</span>
                </Link>
              );
            })}
          </nav>

          <Link
            to="/"
            className="hidden md:flex items-center space-x-1 text-xs font-semibold text-slate-500 hover:text-blue-600 dark:hover:text-white px-2 py-1 rounded transition"
            title="Return to Public Landing Page"
          >
            <span>Landing Page</span>
            <ExternalLink className="w-3 h-3" />
          </Link>
        </div>
      </div>
    </header>
  );
}
